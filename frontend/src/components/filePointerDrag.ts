type Options = {
  type: string;
  data: string;
  label: string;
  count: number;
  onStart: () => void;
  onEnd: () => void;
};

// Use pointer input for drags inside the file browser. Starting a native HTML
// drag suppresses wheel events in WebView2. Reuse the existing drop handlers
// without entering that native drag loop; desktop file drops still use it.
export function startFilePointerDrag(
  source: HTMLElement,
  initial: PointerEvent,
  options: Options,
): () => void {
  const root = source.closest(".file-browser");
  if (!root) return () => {};
  const capture = { capture: true };
  const transfer = new DataTransfer();
  transfer.setData(options.type, options.data);
  transfer.effectAllowed = "copy";
  let started = false;
  let finished = false;
  let preview: HTMLDivElement | null = null;
  let previousTarget: Element | null = null;

  const dispatch = (target: EventTarget, type: string, event: MouseEvent, relatedTarget: EventTarget | null = null) =>
    target.dispatchEvent(new DragEvent(type, {
      bubbles: true,
      cancelable: true,
      clientX: event.clientX,
      clientY: event.clientY,
      dataTransfer: transfer,
      relatedTarget,
    }));

  const suppressClick = (event: Event) => {
    event.preventDefault();
    event.stopImmediatePropagation();
  };

  const finish = () => {
    if (finished) return;
    finished = true;
    window.removeEventListener("pointermove", move, capture);
    window.removeEventListener("pointerup", release, capture);
    window.removeEventListener("pointercancel", cancel, capture);
    window.removeEventListener("keydown", key, capture);
    window.removeEventListener("blur", cancel);
    document.removeEventListener("visibilitychange", hide);
    if (source.hasPointerCapture(initial.pointerId)) source.releasePointerCapture(initial.pointerId);
    preview?.remove();
    if (started) {
      // Keep the capture listener through the click generated by pointerup.
      window.setTimeout(() => window.removeEventListener("click", suppressClick, capture), 0);
      dispatch(source, "dragend", initial);
    }
    options.onEnd();
  };

  const targetAt = (event: MouseEvent) => {
    const hit = document.elementFromPoint(event.clientX, event.clientY);
    return hit?.closest(".file-browser") === root && hit.closest(".file-pane-body") ? hit : null;
  };

  const update = (event: MouseEvent) => {
    const target = targetAt(event);
    if (previousTarget?.closest(".file-pane-body") !== target?.closest(".file-pane-body")) {
      if (previousTarget) dispatch(previousTarget, "dragleave", event, target);
    }
    previousTarget = target;
    const allowed = target ? !dispatch(target, "dragover", event) : false;
    if (preview) {
      preview.style.left = `${Math.max(0, Math.min(event.clientX + 16, window.innerWidth - preview.offsetWidth - 8))}px`;
      preview.style.top = `${Math.max(0, Math.min(event.clientY + 16, window.innerHeight - preview.offsetHeight - 8))}px`;
      preview.classList.toggle("file-drag-blocked", !allowed);
    }
    return allowed ? target : null;
  };

  function move(event: PointerEvent) {
    if (finished || event.pointerId !== initial.pointerId) return;
    if (!started) {
      if (Math.hypot(event.clientX - initial.clientX, event.clientY - initial.clientY) < 6) return;
      started = true;
      preview = document.createElement("div");
      preview.className = "file-drag-preview";
      const count = document.createElement("span");
      count.className = "file-drag-preview-count";
      count.textContent = String(options.count);
      const label = document.createElement("span");
      label.textContent = options.label;
      const hint = document.createElement("small");
      hint.textContent = "Scroll to find a folder";
      preview.append(count, label, hint);
      document.body.append(preview);
      window.addEventListener("click", suppressClick, capture);
      options.onStart();
    }
    event.preventDefault();
    update(event);
  }

  function release(event: PointerEvent) {
    if (finished || event.pointerId !== initial.pointerId) return;
    try {
      if (started) {
        event.preventDefault();
        const target = update(event);
        if (target) dispatch(target, "drop", event);
      }
    } finally {
      finish();
    }
  }

  function cancel() { finish(); }
  function key(event: KeyboardEvent) {
    if (event.key === "Escape") {
      event.preventDefault();
      event.stopPropagation();
      finish();
    }
  }
  function hide() { if (document.hidden) finish(); }

  source.setPointerCapture(initial.pointerId);
  window.addEventListener("pointermove", move, { capture: true, passive: false });
  window.addEventListener("pointerup", release, capture);
  window.addEventListener("pointercancel", cancel, capture);
  window.addEventListener("keydown", key, capture);
  window.addEventListener("blur", cancel);
  document.addEventListener("visibilitychange", hide);
  return finish;
}
